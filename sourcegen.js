const origSrc = await fetch(
	"https://github.com/minh-ton/reynard-browser/releases/download/0.0.1-a1/source.json",
);
const origAltSource = /** @type {AltSource} */ (await origSrc.json());

// Filter out old versions
altSource.apps[0].versions = origAltSource.apps[0].versions.filter((appVersion) => {
	const version = appVersion.version.split(".").map((str) => parseInt(str));
	if (version[0] > firstVersion[0]) return true;
	if (version[0] == firstVersion[0] && version[1] > firstVersion[1])
		return true;
	if (
		version[0] == firstVersion[0] &&
		version[1] == firstVersion[1] &&
		version[2] >= firstVersion[2]
	)
		return true;
	return false;
});

// Replace their repo id with ours
for (const appVersion of altSource.apps[0].versions) {
	appVersion.downloadURL = appVersion.downloadURL.replace("minh-ton/reynard-browser", repoID);
}

process.stdout.write(JSON.stringify(altSource));


